import 'dotenv/config';
import express from 'express';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {initStore} from './lib/store.js';
import {seedDemo} from './lib/seed.js';
import api from './lib/api.js';
const app=express(),root=path.dirname(fileURLToPath(import.meta.url));
app.disable('x-powered-by');
app.use((req,res,next)=>{res.set({'X-Content-Type-Options':'nosniff','X-Frame-Options':'DENY','Referrer-Policy':'strict-origin-when-cross-origin','Content-Security-Policy':"default-src 'self'; script-src 'self'; style-src 'self' 'unsafe-inline' https://fonts.googleapis.com; font-src 'self' https://fonts.gstatic.com; img-src 'self' https: data:; connect-src 'self'; media-src 'self' https:; frame-src https://www.youtube-nocookie.com; base-uri 'self'; form-action 'self'; frame-ancestors 'none'"});next();});
app.use(express.json({limit:'64kb'}));
app.use('/api',api);
app.use('/api',(_req,res)=>res.status(404).json({error:'Endpoint not found.'}));
app.use(express.static(path.join(root,'public')));
app.get('/health',(_req,res)=>res.json({status:'ok'}));
app.get('*',(_req,res)=>res.sendFile(path.join(root,'index.html')));
app.use((err,req,res,_next)=>{if(!err.status)console.error('Request failed:',err.name);res.status(err.status||500).json({error:err.status?err.message:'Unable to complete this request. Please try again.'});});
await initStore();await seedDemo();
app.listen(process.env.PORT||3000,process.env.HOST||'127.0.0.1',()=>console.log(`Blessed Vines School: http://localhost:${process.env.PORT||3000}`));
